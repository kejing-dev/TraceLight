"""Trace Light icon: the PICO 3D icon layers and the 512 export, drawn from the same shapes as the adaptive icon
(`res/drawable/ic_launcher_foreground.xml` on `@color/ic_launcher_background`).

    python tools/make_icon.py [export.png]

Layer 0: the lightbox-paper cream tile. Layer 1: a trace-blue cube drawn in lines (hidden edges dashed) with a
graphite pencil touching its corner and the amber pen-tip dot. Coordinates are the vector's 108-unit viewport.
"""
import os
import sys
from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
S = 1024
K = S / 108.0
CREAM = (242, 230, 204, 255)
BLUE = (47, 123, 255, 255)
GRAPHITE = (58, 63, 71, 255)
WOOD = (232, 196, 140, 255)
AMBER = (255, 182, 72, 255)

FRONT = [(34, 50), (58, 50), (58, 74), (34, 74)]
BACK = [(48, 36), (72, 36), (72, 60), (48, 60)]
SOLID = [(FRONT[0], FRONT[1]), (FRONT[1], FRONT[2]), (FRONT[2], FRONT[3]), (FRONT[3], FRONT[0]),
         (BACK[0], BACK[1]), (BACK[1], BACK[2]), (FRONT[0], BACK[0]), (FRONT[1], BACK[1]), (FRONT[2], BACK[2])]
DASHED = [(BACK[2], BACK[3]), (BACK[3], BACK[0]), (FRONT[3], BACK[3])]
# pencil: tip at the front square's lower right corner, body to the lower right
TIP = (59.5, 75.5)
CONE_END = (66.5, 82.5)
BODY_END = (80, 96)
HALF = 4.2
STROKE = 2.6


def tile():
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(im).rounded_rectangle((40, 40, S - 40, S - 40), radius=220, fill=CREAM)
    return im


def p(xy):
    return (xy[0] * K, xy[1] * K)


def dashes(a, b, n=4):
    out = []
    for i in range(n):
        t0 = i / n
        t1 = t0 + 0.55 / n
        out.append(((a[0] + (b[0] - a[0]) * t0, a[1] + (b[1] - a[1]) * t0), (a[0] + (b[0] - a[0]) * t1, a[1] + (b[1] - a[1]) * t1)))
    return out


def pencil_polys():
    import math
    dx, dy = BODY_END[0] - TIP[0], BODY_END[1] - TIP[1]
    l = math.hypot(dx, dy)
    nx, ny = -dy / l * HALF, dx / l * HALF
    cone = [TIP, (CONE_END[0] + nx, CONE_END[1] + ny), (CONE_END[0] - nx, CONE_END[1] - ny)]
    body = [(CONE_END[0] + nx, CONE_END[1] + ny), (BODY_END[0] + nx, BODY_END[1] + ny), (BODY_END[0] - nx, BODY_END[1] - ny), (CONE_END[0] - nx, CONE_END[1] - ny)]
    lead_end = (TIP[0] + dx / l * 2.6, TIP[1] + dy / l * 2.6)
    lead = [TIP, (lead_end[0] + nx * 0.38, lead_end[1] + ny * 0.38), (lead_end[0] - nx * 0.38, lead_end[1] - ny * 0.38)]
    return cone, body, lead


def front():
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    w = int(STROKE * K)
    for a, b in SOLID:
        d.line((p(a), p(b)), fill=BLUE, width=w)
    for a, b in DASHED:
        for s0, s1 in dashes(a, b):
            d.line((p(s0), p(s1)), fill=BLUE, width=w)
    for c in FRONT + BACK[:3]:
        r = STROKE / 2 * K
        d.ellipse((p(c)[0] - r, p(c)[1] - r, p(c)[0] + r, p(c)[1] + r), fill=BLUE)
    cone, body, lead = pencil_polys()
    d.polygon([p(x) for x in body], fill=GRAPHITE)
    d.polygon([p(x) for x in cone], fill=WOOD)
    d.polygon([p(x) for x in lead], fill=GRAPHITE)
    r = 3.6 * K
    c = p(FRONT[0])
    d.ellipse((c[0] - r, c[1] - r, c[0] + r, c[1] + r), fill=AMBER)
    return im


def vector():
    def path(points, close=True):
        s = "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in points)
        return s + ("z" if close else "")
    lines = []
    for a, b in SOLID:
        lines.append(f'    <path android:strokeColor="#FF2F7BFF" android:strokeWidth="{STROKE}" android:strokeLineCap="round" android:pathData="{path([a, b], False)}" />')
    for a, b in DASHED:
        for s0, s1 in dashes(a, b):
            lines.append(f'    <path android:strokeColor="#FF2F7BFF" android:strokeWidth="{STROKE}" android:pathData="{path([s0, s1], False)}" />')
    cone, body, lead = pencil_polys()
    lines.append(f'    <path android:fillColor="#FF3A3F47" android:pathData="{path(body)}" />')
    lines.append(f'    <path android:fillColor="#FFE8C48C" android:pathData="{path(cone)}" />')
    lines.append(f'    <path android:fillColor="#FF3A3F47" android:pathData="{path(lead)}" />')
    cx, cy = FRONT[0]
    lines.append(f'    <path android:fillColor="#FFFFB648" android:pathData="M{cx - 3.6:.2f},{cy:.2f}a3.6,3.6 0,1 1,7.2,0a3.6,3.6 0,1 1,-7.2,0z" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/make_icon.py: a trace-blue cube (hidden edges dashed), a graphite pencil on its corner, the amber pen tip -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            + "\n".join(lines) + "\n</vector>\n")


def alpha_white(im):
    w = Image.new("RGBA", im.size, (255, 255, 255, 0))
    w.putalpha(im.split()[3])
    return w


def main():
    l0, l1 = tile(), front()
    draw = os.path.join(RES, "drawable")
    l0.save(os.path.join(draw, "icon_3d_layer_0.png"))
    l1.save(os.path.join(draw, "icon_3d_layer_1.png"))
    alpha_white(l0).save(os.path.join(draw, "icon_3d_sdf_0.png"))
    alpha_white(l1).save(os.path.join(draw, "icon_3d_sdf_1.png"))
    with open(os.path.join(draw, "ic_launcher_foreground.xml"), "w", encoding="utf-8") as f:
        f.write(vector())
    if len(sys.argv) > 1:
        Image.alpha_composite(l0, l1).resize((512, 512), Image.LANCZOS).save(sys.argv[1])
    print("icon layers written")


if __name__ == "__main__":
    main()
